/**
 * Inline the printed template diagrams for the PDF renderer.
 *
 * The renderer aborts every network request except `data:` — a sheet document
 * must not be able to fetch anything — so an `<img>` pointing at the
 * application comes out blank in a PDF. This copies the files the web app
 * serves into a generated module keyed by the path each template definition
 * names, so the two can never disagree about which picture is which.
 *
 * Run after adding or replacing a diagram, and commit the result:
 *   node scripts/templates/inline-diagrams.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const publicRoot = join(root, "apps", "web", "public", "templates");
const output = join(root, "packages", "sheet-document", "src", "diagram-assets.ts");

const mediaTypes = {
  ".jpeg": "image/jpeg",
  ".jpg": "image/jpeg",
  ".png": "image/png",
  ".svg": "image/svg+xml",
};

const entries = [];
for (const group of readdirSync(publicRoot).sort()) {
  const dir = join(publicRoot, group);
  for (const file of readdirSync(dir).sort()) {
    const extension = file.slice(file.lastIndexOf("."));
    const mediaType = mediaTypes[extension];
    if (!mediaType) continue;
    // An SVG is text, and a Windows checkout turns its line endings into
    // CRLF. Inline it as the repository stores it, LF, so the generated
    // module is the same whichever machine regenerates it.
    const contents = readFileSync(join(dir, file));
    const base64 =
      extension === ".svg"
        ? Buffer.from(contents.toString("utf8").replace(/\r\n/g, "\n"), "utf8").toString("base64")
        : contents.toString("base64");
    entries.push(
      `  "/templates/${group}/${file}":\n    "data:${mediaType};base64,${base64}",`,
    );
  }
}

writeFileSync(
  output,
  `/**
 * Printed diagrams, inlined.
 *
 * The PDF renderer aborts every network request except \`data:\` — a sheet
 * document must not be able to fetch anything — so an <img> pointing at the
 * application would come out blank. These are the same files served from
 * apps/web/public, keyed by the path the template definition names, and are
 * regenerated by scripts/templates/inline-diagrams.mjs.
 *
 * GENERATED — do not edit by hand.
 */
export const DIAGRAM_DATA_URIS: Record<string, string> = {
${entries.join("\n")}
};
`,
  "utf8",
);

console.log(`inlined ${entries.length} diagrams`);
