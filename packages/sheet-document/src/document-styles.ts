    // Several values in one box: the printed words keep their room.
    ".withunit.joined .unit{flex:none;padding:0 1mm}",
    ".unit{white-space:nowrap}",
    ".letterhead{margin-bottom:2mm}",
    ".letterhead img{width:100%;height:auto}",
    ".matrix .note{display:block;font-size:6.5pt;font-weight:400}",
    ".grid td.diagonal{background-image:linear-gradient(to top right,transparent calc(50% - .18mm),#222 calc(50% - .18mm),#222 calc(50% + .18mm),transparent calc(50% + .18mm))}",
    ".grid.fixed-rows th{padding:1.2mm .6mm;overflow-wrap:break-word}",
    ".grid td.legend{height:13mm;padding:1.5mm 2mm;text-align:right;vertical-align:bottom;white-space:pre-line}",
    ".grid td.legend.start{text-align:left;vertical-align:middle;height:18mm}",
    ".header.title-fields-right{grid-template-columns:2fr 1fr;align-items:center}",
    ".header.title-fields-right h1{grid-column:1;grid-row:1}",
    ".header.title-fields-right .date{grid-column:2;grid-row:1;display:flex;flex-direction:column;gap:1.5mm;font-size:11pt}",
    ".header.title-fields-right .document-code{display:none}",
    ".grouped td{height:7.4mm;padding:.5mm 1.2mm}",
    ".grid th.group-number{border:none;padding:0;text-align:center}",
    ".grid td.group-name{text-align:center}",
    ".group-name .value{writing-mode:vertical-rl;text-orientation:upright;margin:0 auto;font-size:14pt;letter-spacing:.25em}",
    ".grouped tbody.group+tbody.group>tr:first-child>td{border-top-width:.7mm}",
    ".grouped tbody.page-start{break-before:page}",
    ".value.choices{white-space:nowrap}",
    ".grid th.caption-row{position:relative;padding:1.5mm;font-size:13pt;font-weight:500;letter-spacing:.4em}",
