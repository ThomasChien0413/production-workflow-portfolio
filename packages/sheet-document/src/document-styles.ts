    "th.corner .down{position:absolute;bottom:.6mm;left:1mm;font-size:8pt}",
    ".reference{display:flex;gap:4mm;align-items:center;justify-content:space-between;border:.35mm solid #222;margin-top:-.35mm;padding:3mm;break-inside:avoid}",
